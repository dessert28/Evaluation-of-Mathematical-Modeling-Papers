// Run against tests.browser_fixture only. All data and scores below are synthetic.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BROWSER_TEST_URL || 'http://127.0.0.1:8027'
const output = path.resolve('.tmp/browser-acceptance')

async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_TEST_CHANNEL || 'msedge' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(15000)
  const errors = [], consoleErrors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('404')) consoleErrors.push(message.text()) })
  const go = async route => { await page.goto(`${base}/#${route}`); await page.locator('main h1').waitFor() }
  try {
    await go('/overview')
    await page.getByText('暂无评审任务', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'overview-empty.png'), fullPage: true })
    await go('/models')
    await page.getByRole('button', { name: '新增配置', exact: true }).first().click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('提供商', { exact: true }).selectOption('custom')
    await dialog.getByLabel('自定义提供商名称').fill('本地模拟端点')
    await dialog.getByLabel('API Base URL', { exact: true }).fill(`${base}/mock/v1`)
    await dialog.getByLabel('模型名称', { exact: true }).fill('browser-mock')
    const keyInput = dialog.getByLabel(/API Key/)
    await keyInput.pressSequentially('synthetic-test-key')
    assert.equal(await keyInput.inputValue(), 'synthetic-test-key', 'typing must retain modal focus')
    await dialog.getByRole('button', { name: '安全保存' }).click()
    await page.getByText('模型配置已安全保存。', { exact: true }).waitFor()
    const configs = await (await page.request.get(`${base}/api/v1/model-config`)).text()
    assert.ok(!configs.includes('synthetic-test-key'))
    await page.getByRole('button', { name: '测试', exact: true }).click()
    await page.getByText(/连接测试成功/).waitFor()
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    assert.equal(await page.getByRole('dialog').getByLabel(/API Key/).inputValue(), '')
    await page.keyboard.press('Escape')
    await go('/assets')
    await page.locator('input[type=file]').setInputFiles({ name: 'browser-paper.md', mimeType: 'text/markdown', buffer: Buffer.from('# 测试论文\n\n验证数据与模型。<img src=x onerror="window.__injected=true">\n\n| 检查 | 数值 |\n|---|---|\n| 验证误差 | 0.1 |\n') })
    await page.getByRole('button', { name: '查看块' }).click()
    await page.getByRole('dialog').getByText(/验证数据与模型/).waitFor()
    assert.equal(await page.evaluate(() => window.__injected), undefined)
    await page.keyboard.press('Escape')
    await go('/rubrics')
    const rubric = { name: '浏览器验收量表', version: 'v1', criteria: [{ id: 'model', label: '模型质量', weight: 1, scale_min: 0, scale_max: 100 }] }
    await page.locator('input[type=file]').setInputFiles({ name: 'browser-rubric.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(rubric)) })
    await page.getByRole('button', { name: '编辑评分项' }).click()
    dialog = page.getByRole('dialog')
    await dialog.locator('tbody input').nth(2).fill('人工核对后的评分说明')
    await dialog.getByRole('button', { name: '保存草稿' }).click()
    await page.getByRole('button', { name: '确认并发布' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('人工确认理由').fill('测试人员已核对评分条目与权重')
    await dialog.getByRole('button', { name: '我已核对，发布' }).click()
    await page.getByText('已按你的确认发布该量表版本。').waitFor()
    await go('/create')
    await page.getByLabel(/论文资产/).selectOption({ label: 'browser-paper.md' })
    await page.getByLabel(/官方评分标准/).selectOption({ label: '浏览器验收量表 · v1' })
    await page.getByRole('button', { name: '创建并确认启动' }).click()
    dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByRole('button', { name: '确认并启动', exact: true }).isDisabled(), true)
    await dialog.getByLabel('确认理由').fill('核对测试论文及官方量表')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: '确认并启动', exact: true }).click()
    await page.waitForURL('**/#/reviews/*')
    await page.getByText('七阶段已完成，待证据审计', { exact: true }).waitFor({ timeout: 30000 })
    await page.getByText('七阶段总分：80.0 / 100', { exact: true }).waitFor()
    await page.getByText('暂无官方评分', { exact: true }).waitFor()
    // Multi-agent debate: the seven-stage run auto-triggers the debate, so a
    // completed debate snapshot should already be rendered by DebateTimeline.
    await page.getByText('多智能體辯論評審', { exact: true }).waitFor({ timeout: 30000 })
    await page.getByRole('tab', { name: '第 0 輪 · 獨立意見' }).waitFor()
    await page.getByText('目标函数缺少闭环约束（模拟辩论）').waitFor()
    await page.getByText('辯論結論', { exact: true }).waitFor()
    await page.getByText('已收斂', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'debate-desktop.png'), fullPage: true })
    const debateSnapshot = await (await page.request.get(`${base}/api/v1/reviews/${new URL(page.url()).hash.split('/').at(-1)}/debate`)).json()
    assert.equal(debateSnapshot.status, 'COMPLETED')
    assert.ok(debateSnapshot.rounds.length >= 2, 'debate must have round 0 and at least one exchange round')
    assert.ok(debateSnapshot.outcome.converged === true, 'mock panel must converge')
    console.log('  debate panel: COMPLETED, converged, rounds=' + debateSnapshot.rounds.length)
    const reviewId = new URL(page.url()).hash.split('/').at(-1)
    // Add an explicitly synthetic suggestion through the existing manual result API.
    const result = await (await page.request.get(`${base}/api/v1/reviews/${reviewId}/result`)).json()
    result.recommendations = [{ id: 'recommendation-browser', finding_id: result.findings[0].id, action: '补充验证（测试夹具）', acceptance: '记录独立数据误差', priority: 'minor', evidence_ids: [result.evidence[0].id] }]
    assert.equal((await page.request.put(`${base}/api/v1/reviews/${reviewId}/result`, { data: result })).status(), 200)
    await page.reload()
    await page.getByRole('button', { name: '编辑建议' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('修改动作').fill('增加独立数据验证（人工测试）')
    await dialog.getByLabel('验收条件').fill('独立误差和随机种子均有记录')
    await dialog.getByLabel('负责人').fill('测试作者')
    await dialog.getByLabel('修改理由').fill('核对证据后修订建议')
    await dialog.getByRole('button', { name: '保存人工修改' }).click()
    await page.getByText(/理由：核对证据后修订建议/).waitFor()
    await page.getByRole('button', { name: /^证据 evidence-/ }).first().click()
    await page.getByRole('dialog').getByText(/原文块/).waitFor()
    await page.keyboard.press('Escape')
    const downloading = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载 Markdown' }).click()
    const download = await downloading
    assert.equal(download.suggestedFilename(), `review-${reviewId}.md`)
    await download.saveAs(path.join(output, download.suggestedFilename()))
    await page.screenshot({ path: path.join(output, 'review-desktop.png'), fullPage: true })
    await page.getByRole('button', { name: '重跑', exact: true }).first().click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('重跑原因').fill('验证阶段轮询和下游失效行为')
    await dialog.getByRole('button', { name: '确认重跑' }).click()
    await page.getByText('存在 stale 输入或阶段依赖，不显示正式总分。').waitFor()
    const deadline = Date.now() + 15000
    while ((await (await page.request.get(`${base}/api/v1/reviews/${reviewId}/progress`)).json()).run_status === 'RUNNING') {
      assert.ok(Date.now() < deadline); await new Promise(resolve => setTimeout(resolve, 300))
    }
    const protectedResult = await (await page.request.get(`${base}/api/v1/reviews/${reviewId}/result`)).json()
    assert.equal(protectedResult.recommendations[0].action, '增加独立数据验证（人工测试）')
    assert.equal(protectedResult.metadata.recommendation_originals['recommendation-browser'].action, '补充验证（测试夹具）')
    const previousJob = await (await page.request.get(`${base}/api/v1/reviews/${reviewId}`)).json()
    const pending = await (await page.request.post(`${base}/api/v1/reviews`, { data: { asset_id: previousJob.asset_id, rubric_profile_id: previousJob.rubric_profile_id } })).json()
    await go(`/reviews/${pending.id}`)
    await page.getByRole('button', { name: '继续确认并启动' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('继续理由').fill('跨页面核对冻结输入并继续任务')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: '继续运行', exact: true }).click()
    await page.getByText('七阶段已完成，待证据审计', { exact: true }).waitFor({ timeout: 30000 })
    await go('/history')
    await page.getByLabel(/任务状态/).selectOption('EVIDENCE_AUDIT')
    await page.locator('tbody tr').waitFor()
    assert.equal(await page.locator('tbody tr').count(), 1)
    await go('/overview')
    await page.getByText('browser-mock', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'overview-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '打开导航' }).click()
    await page.getByRole('dialog', { name: '工作区导航' }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.equal(await page.getByRole('button', { name: '打开导航' }).evaluate(element => document.activeElement === element), true)
    await page.screenshot({ path: path.join(output, 'overview-mobile.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    assert.deepEqual(errors, [], 'no uncaught browser errors')
    assert.deepEqual(consoleErrors, [], 'no unexpected console errors')
    console.log('PASS: browser mock end-to-end, evidence, edits, download, rerun, XSS, desktop/mobile keyboard')
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
    console.error('Browser errors:', errors, consoleErrors)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
